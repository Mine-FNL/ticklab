/**
 * Fee Revenue Model
 * 
 * Uniswap V3 fee calculation:
 * - Each swap pays a fee (e.g., 0.30% for 3000 bps tier)
 * - Fees are accrued to liquidity providers proportionally
 * - Your fee share = (your_liquidity / pool_liquidity) * fees_in_range
 * 
 * Fee tiers:
 * - 100 bps (0.01%): Stablecoin pairs, lowest IL, lowest fees
 * - 500 bps (0.05%): Stablecoin pairs, moderate
 * - 3000 bps (0.30%): Standard tier for most pairs
 * - 10000 bps (1.00%): Exotic pairs, highest fees, highest IL risk
 * 
 * Key formulas:
 * - fee_rate = fee_tier / 1000000 (e.g., 3000/1000000 = 0.003)
 * - fees_per_day = volume_24h * fee_rate * (your_liquidity / pool_liquidity)
 * - time_in_range_factor = probability of price staying in range
 */

/**
 * Fee tier descriptor
 */
export interface FeeTier {
  /** Basis points (100 = 0.01%, 3000 = 0.30%) */
  bps: number;
  /** Human readable label */
  label: string;
  /** Typical use case */
  description: string;
  /** Recommended for pairs with this vol profile */
  recommendedVol: 'low' | 'medium' | 'high';
}

